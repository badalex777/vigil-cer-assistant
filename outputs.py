"""
Vigil - auditable output set: shared foundation (Block 4).

Every document in the set (CEP, Search Protocol, Search Report, CER first draft,
Evidence Traceability Matrix, Audit Trail) opens with an IDENTICAL control block and
the same mandatory disclaimer. The control block ties the document to ONE immutable
run (run_id + scope_hash + profile_version), which is what turns a pile of separate
files into a coherent, auditable evidence set - and makes post-hoc tampering detectable.

This module is intentionally deterministic and AI-free. It renders structure and
metadata only; no judgement, no narrative.
"""
from __future__ import annotations
import time


# The disclaimer that MUST appear on every document. It encodes the Vigil red line:
# the system describes evidence and never concludes on safety/performance/equivalence/
# conformity - those are the manufacturer's (PRRC's) determinations.
MANDATORY_DISCLAIMER = (
    "AI-GENERATED FIRST DRAFT - REQUIRES PRRC REVIEW. This document is produced by an "
    "automated assistant to support, not replace, the work of a qualified Person "
    "Responsible for Regulatory Compliance (PRRC) or clinical evaluator. It must be "
    "reviewed, completed where marked, and signed by that person. It is not a final "
    "regulatory deliverable until reviewed and signed. Vigil describes evidence; it does "
    "not conclude on safety, performance, equivalence, or regulatory conformity - those "
    "determinations are the manufacturer's responsibility."
)

# Tool identifier stamped on outputs (version travels with the document for audit).
SOURCE_TOOL = "Vigil CER Literature Review Assistant"
TOOL_VERSION = "0.4-demo"


def _utc_now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _as_text(value) -> str:
    """Render a field that may be a string or a list as clean comma-separated text
    (avoids Python list repr like ['a', 'b'] leaking into regulatory documents)."""
    if isinstance(value, (list, tuple)):
        return ", ".join(str(v) for v in value if v)
    return str(value) if value else ""


def build_control_block(profile, run_id: str, document_title: str,
                        document_version: str = "1.0",
                        scope_hash: str | None = None,
                        generated_at_utc: str | None = None) -> dict:
    """Assemble the control-block fields for a document. Deterministic.

    scope_hash defaults to the profile's run_scope_hash() (the frozen scope); pass the
    run's locked_scope_hash explicitly when rendering for a locked run so the document
    carries the value that was stamped at lock time.
    """
    return {
        "document_title": document_title,
        "document_version": document_version,
        "generated_at_utc": generated_at_utc or _utc_now(),
        "run_id": run_id,
        "scope_hash": scope_hash or profile.run_scope_hash(),
        "profile_version": getattr(profile, "profile_version", ""),
        "device_name": profile.device_name,
        "manufacturer": getattr(profile, "manufacturer", ""),
        "is_legacy_device": getattr(profile, "is_legacy_device", False),
        "evaluator_name": getattr(profile, "evaluator_name", "") or "[PRRC TO COMPLETE]",
        "evaluator_qualifications": (
            getattr(profile, "evaluator_qualifications", "") or "[PRRC TO COMPLETE]"),
        "declaration_of_interest_ref": (
            getattr(profile, "declaration_of_interest_ref", "") or "[PRRC TO COMPLETE]"),
        "source_tool": f"{SOURCE_TOOL} v{TOOL_VERSION}",
    }


def render_control_block_md(cb: dict) -> str:
    """Render the control block as a Markdown header block. Identical layout across
    all six documents so an auditor reads the same provenance fields every time."""
    legacy = "Yes (MDD/AIMDD legacy device, MDR transition)" if cb["is_legacy_device"] else "No"
    lines = [
        f"# {cb['document_title']}",
        "",
        "| Control field | Value |",
        "|---|---|",
        f"| Document version | {cb['document_version']} |",
        f"| Generated (UTC) | {cb['generated_at_utc']} |",
        f"| Run ID | {cb['run_id']} |",
        f"| Scope hash | `{cb['scope_hash']}` |",
        f"| Device profile version | {cb['profile_version']} |",
        f"| Device | {cb['device_name']} |",
        f"| Manufacturer | {cb['manufacturer']} |",
        f"| Legacy device | {legacy} |",
        f"| Evaluator (PRRC) | {cb['evaluator_name']} |",
        f"| Evaluator qualifications | {cb['evaluator_qualifications']} |",
        f"| Declaration of interests | {cb['declaration_of_interest_ref']} |",
        f"| Generated by | {cb['source_tool']} |",
        "",
        "> **" + MANDATORY_DISCLAIMER + "**",
        "",
        "---",
        "",
    ]
    return "\n".join(lines)


def document_header_md(profile, run_id: str, document_title: str,
                       document_version: str = "1.0",
                       scope_hash: str | None = None) -> str:
    """Convenience: build + render the control-block header for a document in one call."""
    cb = build_control_block(profile, run_id, document_title,
                             document_version=document_version, scope_hash=scope_hash)
    return render_control_block_md(cb)


# A reusable marker for PRRC-only judgement placeholders, so they are visually
# unmistakable in every document and easy to assert on in tests.
def prrc_placeholder(label: str, guidance: str = "") -> str:
    """Render a clearly-marked PRRC judgement placeholder. The system inserts these
    wherever a determination (equivalence, benefit-risk, residual risk, GSPR conformity,
    conclusions) is required - it never fills them."""
    block = f"> **[PRRC JUDGEMENT REQUIRED: {label}]**"
    if guidance:
        block += f"\n>\n> {guidance}"
    return block


# --- Document 1: CEP (Clinical Evaluation Plan) ------------------------------
# Stage 0 (scope). Deterministic from the locked profile + approved search strings.
# Downloadable the moment Start Research is pressed - before any results exist.
# Hard rules: MDR Annex XIV Part A.1a. Legacy additions: MDCG 2020-6 Appendix II.

def generate_cep_md(profile, run_id: str, approved_queries: dict | None = None,
                    scope_hash: str | None = None) -> str:
    """Render the Clinical Evaluation Plan as Markdown. Deterministic (no AI).

    approved_queries: the PRRC-approved search strings (verbatim), if available. The CEP
    can render from the profile alone (at lock time the strings are already approved)."""
    out = [document_header_md(profile, run_id, "Clinical Evaluation Plan (CEP)",
                              scope_hash=scope_hash)]
    a = out.append

    a("## 1. Purpose and regulatory basis\n")
    a("This Clinical Evaluation Plan (CEP) defines the scope and method of the clinical "
      "evaluation BEFORE it is executed, per MDR 2017/745 Annex XIV Part A Section 1a. "
      "Method follows MEDDEV 2.7/1 rev 4 (Stage 0). "
      + ("This is a legacy device (CE-marked under MDD/AIMDD) in MDR transition; the plan "
         "additionally follows MDCG 2020-6 Appendix II.\n" if profile.is_legacy_device
         else "\n"))

    a("## 2. Device and intended purpose\n")
    a(f"- **Device:** {profile.device_name}")
    a(f"- **Manufacturer:** {getattr(profile, 'manufacturer', '')}")
    a(f"- **Description:** {profile.device_description}")
    a(f"- **Intended purpose:** {profile.intended_purpose}")
    a(f"- **Classification:** {profile.classification} "
      f"(rule {profile.classification_rule})")
    if profile.is_well_established_technology:
        a("- **Well-established technology (MDR Art. 61(8)):** Yes - relatively simple/"
          "stable design, well-known safety and performance profile, long market history. "
          "[PRRC to confirm WET status against all criteria.]")
    a("")

    a("## 3. Intended target groups, indications and contra-indications\n")
    a(f"- **Target population:** {profile.pico_population or '[to be specified]'}")
    a(f"- **Medical condition(s):** {', '.join(profile.medical_condition) or '[to be specified]'}")
    a(f"- **Therapeutic area:** {_as_text(profile.therapeutic_area) or '[to be specified]'}")
    a("- **Indications / contra-indications:** as per the device IFU. "
      "[PRRC to confirm alignment of this plan with the current IFU, label and "
      "promotional materials per MDCG 2020-6.]")
    a("")

    a("## 4. Identification of relevant GSPRs requiring clinical data\n")
    if profile.relevant_gspr:
        for g in profile.relevant_gspr:
            a(f"- {g}")
    else:
        a("- [PRRC to identify the General Safety and Performance Requirements "
          "(MDR Annex I) for which demonstration of conformity requires clinical data.]")
    a("\n*Identification only. Demonstration of conformity to each GSPR is a PRRC "
      "judgement made in the CER, not by this system.*\n")

    a("## 5. Intended clinical benefits and outcome parameters\n")
    a(f"- **Intended clinical benefit / outcomes:** {profile.pico_outcomes or '[to be specified]'}")
    a("- [PRRC to specify the relevant, measurable clinical outcome parameters per "
      "MDR Annex XIV 1a and MEDDEV A7.2.]")
    a("")

    a("## 6. Review questions (PICO) and search strategy\n")
    a("Two mandatory search tracks (MEDDEV A5.2):\n")
    a(f"- **Track 1 (device-specific):** In {profile.pico_population or '[population]'} "
      f"with {', '.join(profile.medical_condition) or '[condition]'}, what is the clinical "
      f"safety and performance of {profile.device_name}"
      + (f" compared to {profile.pico_comparator}" if profile.pico_comparator else "")
      + f" in terms of {profile.pico_outcomes or '[outcomes]'}?")
    a(f"- **Track 2 (state of the art):** What is the current state of the art for "
      f"managing {', '.join(profile.medical_condition) or '[condition]'} using "
      f"{', '.join(profile.technology_category) or '[technology]'}, in terms of clinical "
      f"benchmarks and known risks?")
    a("")
    a("**Databases searched, with justification:**")
    a("- *PubMed/MEDLINE* - the most comprehensive biomedical index for device clinical "
      "evaluation; searched comprehensively.")
    a("- *ClinicalTrials.gov* - trial registrations, including unpublished studies "
      "(publication-bias check expected by Notified Bodies).")
    a("- *Embase / Cochrane (if available to the PRRC)* - searched by the PRRC in their "
      "own subscription and the export ingested; the PRRC owns those search strategies.")
    a("")
    if approved_queries:
        a("**Approved search strings (verbatim, frozen at protocol sign-off):**\n")
        for track, q in approved_queries.items():
            a(f"- **{track}:**\n```\n{q}\n```")
    else:
        a("*Search strings are frozen at the protocol approval gate and reproduced in "
          "the Literature Search Protocol.*")
    a(f"\n- **Date range:** {profile.date_from} to {profile.date_to}")
    a(f"- **Languages:** {', '.join(profile.languages) or 'English'}")
    a("")

    a("## 7. State of the art - alternative treatments strategy\n")
    if profile.is_legacy_device and profile.alternative_treatments_strategy:
        a(profile.alternative_treatments_strategy)
    else:
        a("The Track 2 search and clinical practice guidelines characterise current "
          "treatment alternatives and benchmarks for the medical condition. "
          "[PRRC to confirm the strategy to identify and assess alternative treatments, "
          "MDR Art. 61(3)(c).]")
    a("\n*Note: state-of-the-art / similar-device data is supportive CONTEXT and does "
      "NOT constitute clinical data under the MDR (MDCG 2020-6).*\n")

    a("## 8. Equivalence\n")
    if profile.equivalence_claimed:
        a(f"Equivalence is claimed to: "
          f"{', '.join(profile.equivalent_device_names())}.")
        a("The equivalence demonstration (technical / biological / clinical "
          "characteristics per MDCG 2020-5), full disclosure of differences, and "
          "justification are assembled in the CER. Access to the equivalent device's "
          "technical documentation on an ongoing basis is required (MDR Annex XIV / "
          "MDCG 2020-5). [PRRC to attest access and determine whether equivalence holds.]")
    else:
        a("No equivalence claimed. The clinical evaluation relies on the device's own "
          "data and the literature on the device and its technology.")
    a("")

    a("## 9. Methods for clinical safety examination\n")
    a("Qualitative and quantitative aspects of clinical safety are examined through the "
      "appraised literature, manufacturer-held data (if provided), and post-market data. "
      "Determination of residual risks and side-effects, and their acceptability, is a "
      "PRRC judgement.")
    a(prrc_placeholder(
        "Benefit-risk acceptability parameters",
        "Specify, based on the state of the art in medicine, the parameters used to "
        "determine the acceptability of the benefit-risk ratio for each indication and "
        "for the intended purpose (MDR Annex XIV 1a)."))
    a("")

    if profile.is_legacy_device:
        a("## 10. Legacy device: clinical evidence and PMS strategy (MDCG 2020-6)\n")
        a("**Required level of clinical evidence (MDR Art. 61(1)):**")
        a(profile.required_level_of_clinical_evidence
          or "[PRRC to define the level of clinical evidence appropriate to the device "
             "and intended purpose.]")
        a("\n**PMS data collection strategy (MDCG 2020-6 App II):**")
        a(profile.pms_data_collection_strategy
          or "[PRRC to define the strategy to systematically collect, summarise and "
             "assess PMS data demonstrating continuing safety and performance.]")
        a("\n*The sufficient-clinical-evidence hierarchy (MDCG 2020-6 Appendix III, "
          "ranks 1-8) is applied in the CER analysis. Reliance solely on complaints and "
          "vigilance is not sufficient.*\n")
        next_n = 11
    else:
        next_n = 10

    a(f"## {next_n}. Need for clinical investigation / PMCF\n")
    a(prrc_placeholder(
        "Whether clinical investigation and/or PMCF data are required",
        "Indicate whether additional clinical investigation or PMCF data are needed to "
        "demonstrate conformity, based on the identified data and any gaps (MDR Annex "
        "XIV 1a; MEDDEV A2)."))
    a("")

    a(f"## {next_n + 1}. Evaluator\n")
    a(f"- **Evaluator (PRRC):** {profile.evaluator_name or '[to be completed]'}")
    a(f"- **Qualifications:** {profile.evaluator_qualifications or '[to be completed]'}")
    a(f"- **Declaration of interests:** {profile.declaration_of_interest_ref or '[to be attached]'}")
    a("")

    return "\n".join(out)


# --- Document 2: Literature Search Protocol ----------------------------------
# Stage 1 (the PLAN, before execution). Deterministic from approved strings.
# Populates CEAR Section D. Hard rules: MEDDEV Appendix A5.3.

def generate_search_protocol_md(profile, run_id: str, approved_queries: dict,
                                scope_hash: str | None = None,
                                ris_sources: list[str] | None = None) -> str:
    out = [document_header_md(profile, run_id,
                              "Literature Search Protocol", scope_hash=scope_hash)]
    a = out.append

    a("## 1. Background and rationale (MEDDEV A5.1)\n")
    a(f"This protocol plans the literature search for the clinical evaluation of "
      f"{profile.device_name} BEFORE execution (MEDDEV 2.7/1 rev 4 A5.3: \"the purpose "
      f"of a literature search protocol is to plan the search before execution\"). "
      f"The search informs the state-of-the-art assessment and the device-specific "
      f"clinical evidence.")
    if profile.equivalence_claimed:
        a(f"\nEquivalence is claimed to {_as_text(profile.equivalent_device_names())}; "
          f"literature on the equivalent device is sought in Track 1.")
    a("")

    a("## 2. Objective - review questions (PICO, MEDDEV A5.2)\n")
    a(f"- **Track 1 (device-specific):** population {profile.pico_population or '[]'}; "
      f"intervention {profile.pico_intervention or profile.device_name}; "
      f"comparator {profile.pico_comparator or '[]'}; "
      f"outcomes {profile.pico_outcomes or '[]'}.")
    a(f"- **Track 2 (state of the art):** current management of "
      f"{_as_text(profile.medical_condition)} using "
      f"{_as_text(profile.technology_category)}; clinical benchmarks and known risks.")
    a("")

    a("## 3. Methods (MEDDEV A5.3)\n")
    a("### 3.1 Sources and justification\n")
    a("- **PubMed/MEDLINE** - most comprehensive biomedical index for device clinical "
      "evaluation; searched comprehensively (all hits up to the configured cap).")
    a("- **ClinicalTrials.gov** - trial registrations incl. unpublished studies; "
      "supports identification of all data, favourable and unfavourable (publication "
      "bias).")
    if ris_sources:
        for s in ris_sources:
            a(f"- **{s}** - searched by the PRRC in their own institutional subscription; "
              f"results exported (RIS) and ingested. The PRRC owns this search strategy.")
    else:
        a("- **Embase / Cochrane** - searched by the PRRC in their own subscription where "
          "available; results ingested via export. (Not directly connectable: commercial "
          "licences prohibit third-party automated access.)")
    a("")
    a("### 3.2 Search strings (frozen at sign-off, verbatim)\n")
    for track, q in approved_queries.items():
        a(f"**{track}:**\n```\n{q}\n```")
    a(f"- **Date limits:** {profile.date_from} to {profile.date_to}")
    a(f"- **Language limits:** {_as_text(profile.languages) or 'English'}")
    a("")
    a("### 3.3 Selection criteria (locked at sign-off)\n")
    inc, exc = profile.criteria_for_track("device_specific")
    a("**Inclusion (device-specific / Track 1):**")
    for c in inc:
        a(f"- {c}")
    a("\n**Exclusion (device-specific / Track 1):**")
    for c in exc:
        a(f"- {c}")
    inc2, exc2 = profile.criteria_for_track("state_of_art")
    if inc2 != inc or exc2 != exc:
        a("\n**Inclusion (state of the art / Track 2):**")
        for c in inc2:
            a(f"- {c}")
        a("\n**Exclusion (state of the art / Track 2):**")
        for c in exc2:
            a(f"- {c}")
    a("\n*Criteria are LOCKED before execution. The audit trail shows they did not "
      "change between sign-off and search, preventing post-hoc tuning toward favourable "
      "papers (MEDDEV 8.2: thorough and objective; identify all favourable AND "
      "unfavourable data).*\n")

    a("### 3.4 Deduplication strategy\n")
    a("Multi-pass deduplication: (1) PubMed ID, (2) normalized DOI (catches "
      "ahead-of-print and the same study across sources), (3) normalized title, "
      "(4) registry/external id. Trial registrations are not collapsed against "
      "same-title published papers (different evidence types). Duplicate count feeds "
      "the PRISMA 'duplicates removed' box.\n")

    a("### 3.5 Avoiding duplication of manufacturer-held data\n")
    a("Manufacturer-held clinical data (pre-market investigations, PMCF, PMS) enters via "
      "upload, tagged 'Manufacturer-Held Data', and is appraised alongside the literature "
      "- not re-searched in the databases.\n")

    a("### 3.6 Data collection, appraisal and analysis plans\n")
    a("- **Data collection:** abstract screening (Sonnet) against the locked criteria; "
      "full-text retrieval (open access via PMC/Unpaywall) for included records; "
      "deterministic identity verification before any auto-retrieved full text is "
      "appraised.")
    a("- **Appraisal plan:** full-text appraisal (Opus) per MEDDEV Appendix A6, scoring "
      "methodological quality and relevance. Abstract-only records are screening, never "
      "the basis of appraisal.")
    a("- **Analysis plan:** evidence summarised per outcome with citation to source; "
      "for legacy devices, mapped to the sufficient-evidence hierarchy (MDCG 2020-6 "
      "App III). All judgements (benefit-risk, equivalence, conformity) are PRRC's.")
    a("")
    return "\n".join(out)


# --- Document 3: Literature Search Report ------------------------------------
# Stage 1 (what HAPPENED on execution) + PRISMA flow. Deterministic.

def generate_search_report_md(profile, run_id: str, counts, search_meta: dict,
                              prisma_svg: str = "", scope_hash: str | None = None) -> str:
    """counts: a prisma.PrismaCounts (or .as_dict()). search_meta: per-source metadata
    captured during retrieval (totals, capped flags, search dates)."""
    cd = counts.as_dict() if hasattr(counts, "as_dict") else dict(counts)
    out = [document_header_md(profile, run_id,
                              "Literature Search Report", scope_hash=scope_hash)]
    a = out.append

    a("## 1. Execution summary\n")
    a("This report documents the EXECUTION of the search planned in the Literature "
      "Search Protocol (MEDDEV A5.3), to a degree allowing the methods to be appraised "
      "critically, the results verified, and the search reproduced.\n")

    a("## 2. Per-source results and search dates\n")
    a("| Source | Search date (UTC) | Total available | Retrieved | Capped |")
    a("|---|---|---|---|---|")
    if search_meta:
        for src, m in search_meta.items():
            if not isinstance(m, dict) or m.get("error"):
                a(f"| {src} | - | - | - | error: {m.get('error','?') if isinstance(m,dict) else m} |")
                continue
            a(f"| {src} | {m.get('search_date_utc','-')} | "
              f"{m.get('total_available','-')} | {m.get('retrieved','-')} | "
              f"{'yes' if m.get('capped') else 'no'} |")
    else:
        a("| (search metadata not recorded for this run) | - | - | - | - |")
    a("")
    a("*Where total available exceeds retrieved, the difference is recorded (e.g. records "
      "indexed but not retrievable - retracted, ahead-of-print without full metadata). "
      "This per-stage accounting is required by PRISMA 2020.*\n")

    a("## 3. PRISMA 2020 flow\n")
    a(f"- Records identified (databases): {cd.get('db_records',0)}")
    a(f"- Records from registers: {cd.get('register_records',0)}")
    a(f"- Duplicates removed: {cd.get('duplicates_removed',0)}")
    a(f"- Records screened (title/abstract): {cd.get('screened',0)}")
    a(f"- Excluded at screening: {cd.get('excluded_screening',0)}")
    a(f"- Reports sought for retrieval: {cd.get('reports_sought',0)}")
    a(f"- Reports not retrieved (paywalled residual -> PRRC upload): "
      f"{cd.get('reports_not_retrieved',0)}")
    a(f"- Reports assessed (full-text appraisal): {cd.get('assessed',0)}")
    a(f"- Excluded at eligibility: {cd.get('excluded_eligibility',0)}")
    a(f"- **Included in clinical evaluation: {cd.get('included',0)}**")
    a("")
    if prisma_svg:
        a("*(PRISMA 2020 flow diagram rendered separately as SVG and included in the "
          "output package.)*\n")

    a("## 4. Deviations from the protocol\n")
    a(prrc_placeholder(
        "Deviations from the search protocol",
        "Record any deviations from the planned protocol (e.g. supplementary manual "
        "searches the PRRC ran, sources unavailable, adjustments) and their rationale. "
        "If there were no deviations, state 'No deviations.'"))
    a("")
    return "\n".join(out)


# --- Document 5: Evidence Traceability Matrix --------------------------------
# Audit support. Deterministic. Maps each retained record to its source + status.

def generate_traceability_matrix_md(profile, run_id: str, records: list[dict],
                                    scope_hash: str | None = None) -> str:
    """records: the run's retained records (each a dict with id/source/track/verdict)."""
    out = [document_header_md(profile, run_id,
                              "Evidence Traceability Matrix", scope_hash=scope_hash)]
    a = out.append
    a("## Traceability of evidence to source\n")
    a("Each retained record is traceable to its source identifier and evidence type. An "
      "auditor can move from any cited item in the CER to its source in one step "
      "(MEDDEV: results must be verifiable; every claim traceable to source).\n")
    a("| # | Source ID | Source | Evidence type | Track | Screen verdict |")
    a("|---|---|---|---|---|---|")
    for i, r in enumerate(records, 1):
        sid = r.get("pmid") or r.get("registry_id") or r.get("external_id") or "-"
        src = r.get("source", "pubmed")
        etype = r.get("entry_type", "paper")
        etype_label = {
            "paper": "Published Literature",
            "trial_registration": "Trial Registration",
        }.get(etype, etype)
        if src and src not in ("pubmed", "clinicaltrials_gov"):
            etype_label = f"{etype_label} ({src})"
        track = r.get("track", "-")
        verdict = r.get("screen_verdict") or "-"
        a(f"| {i} | {sid} | {src} | {etype_label} | {track} | {verdict} |")
    a("")
    a(f"*Total retained records: {len(records)}. Source types: Published Literature / "
      f"Trial Registration / Manufacturer-Held Data / PMS Signal as applicable.*\n")
    return "\n".join(out)


# --- Document 6: Audit Trail Export (CSV) ------------------------------------
# Audit / QMS support. Deterministic. Formalizes run_log to CSV.

def generate_audit_trail_csv(run_log_rows: list[dict],
                             state_row: dict | None = None) -> str:
    """run_log_rows: list of {ts, stage, message} from db. state_row: the run_state row
    (transition timestamps). Returns CSV text. Fits the client's ISO 13485 4.2.4/4.2.5
    record control."""
    import csv
    import io as _io
    buf = _io.StringIO()
    w = csv.writer(buf)
    w.writerow(["timestamp_utc", "category", "event"])

    def _fmt_ts(ts):
        try:
            return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(float(ts)))
        except (TypeError, ValueError):
            return str(ts)

    # State transitions first (the lifecycle backbone), if provided.
    if state_row:
        for state, col in (("draft", "created_at"), ("strings_approved", "approved_at"),
                           ("locked", "locked_at"), ("running", "running_at"),
                           ("phase_b", "phase_b_at"), ("complete", "complete_at")):
            ts = state_row.get(col)
            if ts:
                extra = ""
                if state == "locked" and state_row.get("locked_scope_hash"):
                    extra = f" (scope_hash={state_row['locked_scope_hash']})"
                if state in ("strings_approved", "locked") and state_row.get("actor"):
                    extra += f" (actor={state_row['actor']})"
                w.writerow([_fmt_ts(ts), "state_transition", f"-> {state}{extra}"])

    # Then the append-only event log.
    for row in run_log_rows:
        w.writerow([_fmt_ts(row.get("ts")), row.get("stage", ""),
                    row.get("message", "")])

    return buf.getvalue()


# --- Document 4: CER First Draft ---------------------------------------------
# Stages 2-4. Full Appendix A9 structure. The ONLY document with AI narrative,
# confined to DESCRIPTIVE sections. Every judgement is a PRRC placeholder.
# Equivalence table is ASSEMBLED (MDCG 2020-5), never judged.

def _equivalence_table_md(profile) -> str:
    """Assemble the 3-characteristic equivalence comparison table (MDCG 2020-5):
    technical / biological / clinical. The system ASSEMBLES from the equivalence
    register and transcribes the PRRC's rationale VERBATIM. It does NOT judge whether
    equivalence holds - that is a PRRC determination (placeholder below the table)."""
    lines = []
    for eq in profile.equivalent_devices:
        if not eq.name:
            continue
        lines.append(f"\n**Claimed equivalent device: {eq.name}**"
                     + (f" ({eq.model})" if getattr(eq, "model", "") else ""))
        lines.append("")
        lines.append("| Characteristic | PRRC rationale (transcribed verbatim) |")
        lines.append("|---|---|")
        tech = getattr(eq, "technical_characteristics", "") or "[PRRC to provide]"
        bio = getattr(eq, "biological_characteristics", "") or "[PRRC to provide]"
        clin = getattr(eq, "clinical_characteristics", "") or "[PRRC to provide]"
        lines.append(f"| Technical | {tech} |")
        lines.append(f"| Biological | {bio} |")
        lines.append(f"| Clinical | {clin} |")
        diffs = getattr(eq, "differences_and_justification", "") \
            or getattr(eq, "differences", "")
        lines.append("")
        lines.append("**Differences disclosed and their justification (MDCG 2020-5 / "
                     "MEDDEV A10 require ALL differences disclosed):**")
        lines.append(diffs or "[PRRC to disclose ALL differences between the device and "
                              "this equivalent, and justify why they do not affect "
                              "clinical performance and safety.]")
        access = getattr(eq, "technical_documentation_access", "")
        lines.append("")
        lines.append(f"**Access to the equivalent's technical documentation (MDR Annex "
                     f"XIV / MDCG 2020-5):** {access or '[PRRC to attest ongoing access.]'}")
    return "\n".join(lines)


def generate_cer_md(profile, run_id: str, appraised_records: list[dict],
                    incomplete_records: list[dict] | None = None,
                    pms_signals: list[dict] | None = None,
                    counts=None, scope_hash: str | None = None,
                    narrative_fn=None) -> str:
    """Render the CER first draft (Appendix A9 structure) as Markdown.

    appraised_records: fully appraised (full-text) records with extraction/appraisal data.
    narrative_fn: callable(section_key, context_dict) -> str that produces AI prose for
        the DESCRIPTIVE sections (device background, state of the art, evidence summary).
        Injectable so tests run offline with a stub and real runs pass an Opus-backed fn.
        If None, descriptive sections render a clearly-marked deterministic placeholder.
    """
    incomplete_records = incomplete_records or []
    pms_signals = pms_signals or []

    def _narr(section_key, context):
        if narrative_fn is None:
            return (f"*[AI narrative for '{section_key}' is generated during a full run "
                    f"from the appraised evidence. Not generated in this offline render.]*")
        return narrative_fn(section_key, context)

    out = [document_header_md(profile, run_id,
                              "Clinical Evaluation Report (CER) - First Draft",
                              scope_hash=scope_hash)]
    a = out.append

    a("## 1. Summary\n")
    a(_narr("summary", {"profile": profile, "n_appraised": len(appraised_records),
                        "appraised": appraised_records}))
    a("")

    a("## 2. Scope of the clinical evaluation\n")
    a(f"- **Device:** {profile.device_name} ({profile.classification}, "
      f"rule {profile.classification_rule})")
    a(f"- **Intended purpose:** {profile.intended_purpose}")
    a(f"- **Target population / conditions:** {profile.pico_population or '[]'}; "
      f"{_as_text(profile.medical_condition)}")
    a("- Scope and method are defined in the Clinical Evaluation Plan (CEP); search in "
      "the Literature Search Protocol and Report.")
    a("")

    a("## 3. Clinical background, current knowledge, state of the art\n")
    a(_narr("state_of_art", {"profile": profile,
                             "condition": _as_text(profile.medical_condition),
                             "technology": _as_text(profile.technology_category),
                             "appraised": appraised_records}))
    a("\n*State-of-the-art / similar-device data is supportive CONTEXT and does not "
      "constitute clinical data under the MDR (MDCG 2020-6).*\n")

    a("## 4. Device under evaluation\n")
    a("### 4.1 Device description and intended purpose\n")
    a(profile.device_description)
    a(f"\nIntended purpose: {profile.intended_purpose}\n")

    a("### 4.2 Equivalence\n")
    if profile.equivalence_claimed:
        a("The following equivalence comparison is ASSEMBLED from the manufacturer's "
          "equivalence register (MDCG 2020-5). The PRRC's rationale is transcribed "
          "verbatim. Vigil does not judge whether equivalence holds.")
        a(_equivalence_table_md(profile))
        a("")
        a(prrc_placeholder(
            "Equivalence determination",
            "Determine whether equivalence is demonstrated for all three characteristics "
            "(technical, biological, clinical) per MDCG 2020-5, taking into account the "
            "disclosed differences. This determination is the PRRC's; Vigil only "
            "assembles the comparison."))
    else:
        a("No equivalence is claimed.")
    a("")

    a("### 4.3 Manufacturer-held clinical data\n")
    mh = [r for r in appraised_records if r.get("source") == "manufacturer_held"]
    if mh:
        a(f"{len(mh)} manufacturer-held data item(s) were ingested and appraised "
          f"alongside the literature (tagged 'Manufacturer-Held Data').")
    else:
        a("No manufacturer-held clinical data was provided for this run. "
          "[PRRC to confirm whether pre-market investigations, PMCF, or PMS records "
          "exist and should be included - MEDDEV 8.1.]")
    a("")

    a("## 5. Summary of the clinical data and appraisal\n")
    a(f"{len(appraised_records)} record(s) were fully appraised (full text, MEDDEV "
      f"Appendix A6). Each claim below is traceable to its source (see Evidence "
      f"Traceability Matrix).")
    if incomplete_records:
        a(f"\n{len(incomplete_records)} record(s) remain 'appraisal incomplete' (no "
          f"open-access full text retrieved; routed to PRRC manual upload). These are "
          f"NOT used as appraised evidence.")
    a("")
    a(_narr("evidence_summary", {"profile": profile,
                                 "appraised": appraised_records}))
    a("")

    a("## 6. Analysis of the clinical data\n")
    a("### 6.1 Performance\n")
    a(_narr("performance", {"appraised": appraised_records}))
    a("\n### 6.2 Safety\n")
    a(_narr("safety", {"appraised": appraised_records}))

    if profile.is_legacy_device:
        a("\n### 6.3 Sufficiency of clinical evidence (legacy device, MDCG 2020-6)\n")
        a("Evidence sources are considered against the sufficient-clinical-evidence "
          "hierarchy (MDCG 2020-6 Appendix III, ranks 1-8). Most appraised literature "
          "falls at rank 4 (quantifiable data with possible methodological limitations); "
          "state-of-the-art context is rank 6 (not clinical data under the MDR). "
          + ("As a well-established technology, cumulative evidence from these sources "
             "may suffice if appropriately appraised. " if profile.is_well_established_technology
             else "")
          + "Reliance solely on complaints and vigilance is not sufficient.")
        a(prrc_placeholder(
            "Sufficiency of clinical evidence for each GSPR",
            "Assess whether the cumulative appraised evidence meets the required level "
            "of clinical evidence for each relevant GSPR (MDCG 2020-6). Narrow the "
            "intended purpose if evidence is insufficient."))
        base = 4
    else:
        base = 3

    a(f"\n### 6.{base} Benefit-risk\n")
    a(prrc_placeholder(
        "Benefit-risk acceptability",
        "Determine, based on the state of the art, whether the benefit-risk profile is "
        "acceptable for each indication and the intended purpose (MEDDEV A10; MDR Annex "
        "I). Vigil presents the evidence; it does not conclude."))
    a(f"\n### 6.{base + 1} Residual-risk acceptability\n")
    a(prrc_placeholder(
        "Residual-risk acceptability",
        "Determine whether residual risks and undesirable side-effects are acceptable "
        "in relation to the benefits and the state of the art (ISO 14971; MEDDEV A10)."))
    a(f"\n### 6.{base + 2} GSPR conformity\n")
    a(prrc_placeholder(
        "Conformity with the relevant GSPRs",
        "Conclude on conformity with each relevant General Safety and Performance "
        "Requirement (MDR Annex I) based on the appraised clinical evidence. This is the "
        "manufacturer's determination."))
    a("")

    a("## 7. PMCF / PMS considerations\n")
    if pms_signals:
        a(f"{len(pms_signals)} CER-relevant post-market signal(s) were surfaced from the "
          f"Vigil PMS Monitor handoff for PRRC triage:")
        for s in pms_signals[:20]:
            sid = s.get("signal_id") or s.get("id") or "-"
            a(f"- [{sid}] {s.get('summary', s.get('description',''))[:160]}")
    else:
        a("No CER-relevant PMS signals were provided for this run.")
    a(prrc_placeholder(
        "PMCF plan and PMS integration",
        "Define the PMCF plan and how PMS data are systematically collected and fed back "
        "into the CER update cycle (MDR Annex XIV Part B; MDCG 2020-7/2020-8)."))
    a("")

    a("## 8. Conclusions\n")
    a(prrc_placeholder(
        "Conclusions of the clinical evaluation",
        "State the conclusions on clinical safety, performance, benefit-risk, and GSPR "
        "conformity. Vigil does NOT write conclusions - it describes evidence."))
    a("")

    a("## 9. Date of next evaluation\n")
    a("The CER is a living document and must be updated as new clinical data become "
      "available through PMS and PMCF (MDR Art. 61, Annex XIV Part A).")
    if profile.is_legacy_device or profile.is_well_established_technology:
        a("\nThis device is characterised as a well-established technology / legacy "
          "device. The update frequency may be less frequent than the annual cycle "
          "required for Class III and implantable devices, BUT the chosen frequency must "
          "be justified based on risk class and technology maturity - Notified Bodies "
          "verify this justification (MDCG 2020-6).")
    interval = getattr(profile, "next_evaluation_interval", "")
    justif = getattr(profile, "next_evaluation_justification", "")
    if interval or justif:
        a("\n**Update frequency (defined by the PRRC):**")
        a(f"- **Interval:** {interval or '[to be specified]'}")
        a(f"- **Justification:** {justif or '[to be specified]'}")
        a("- **Exact date of next evaluation:** fixed at sign-off, calculated from the "
          "release date plus the interval above.")
    else:
        a(prrc_placeholder(
            "Date of next evaluation and justification of update frequency",
            "Set the update interval and justify it based on the device risk class, "
            "technology maturity, rate of PMS/PMCF data accrual, and any emerging risks. "
            "For non-Class III / non-implantable devices the manufacturer defines and "
            "must justify this schedule (MDR Annex XIV Part A; MDCG 2020-6)."))
    a("")

    a("## 10. Dates and signatures\n")
    a(f"- **Evaluator (PRRC):** {profile.evaluator_name or '[to be completed]'}")
    a(f"- **Qualifications:** {profile.evaluator_qualifications or '[to be completed]'}")
    a(f"- **Declaration of interests:** {profile.declaration_of_interest_ref or '[to attach]'}")
    a("- **Statement of agreement:** [Evaluator to confirm agreement with the contents.]")
    a("- **Evaluator signature / date:** ______________________")
    a("- **Manufacturer final release (name / signature / date):** ______________________")
    a("\n> **Evaluator qualification requirement (MDR; MDCG / Notified Body practice):** "
      "The clinical evaluation must be performed and signed by an evaluator with "
      "subject-matter expertise and **clinical specialty relevant to the device's "
      "indication** - not regulatory-affairs staff alone. Notified Bodies flag CERs "
      "lacking appropriate clinical input or documented evaluator independence. The PRRC "
      "must ensure a suitably qualified clinical evaluator authors/co-signs this report.")
    a("\n*The CER must be dated, version-controlled, and signed by the evaluator with CV "
      "and declaration of interests (MEDDEV Section 11 / A9 item 7).*\n")

    a("## 11. References\n")
    refs = []
    for r in appraised_records:
        sid = r.get("pmid") or r.get("registry_id") or r.get("external_id") or "?"
        title = r.get("title", "")
        journal = r.get("journal", "")
        year = r.get("year", "")
        refs.append(f"- [{sid}] {title}. {journal} {year}.".replace("  ", " "))
    if refs:
        out.extend(refs)
    else:
        a("[No appraised references in this run.]")
    a("")
    return "\n".join(out)
