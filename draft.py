"""Vigil - Stage: search report + CER first-draft section assembly."""
from __future__ import annotations
import json

import config
import db
from llm import load_prompt

_SYSTEM = "You write only the requested Markdown. No preamble."


def build_search_report(profile, queries: dict, counts, prisma_svg: str,
                        records: list[dict]) -> str:
    """The audit-ready literature search report - a regulatory artifact submitted
    to the Notified Body. Deterministic; not LLM-generated (it documents the
    protocol verbatim). MEDDEV 2.7/1 rev 4 Appendix A5 structure."""
    incl = [r for r in records if r.get("screen_verdict") == "include"]
    excl = [r for r in records if r.get("screen_verdict") == "exclude"]
    unc = [r for r in records if r.get("screen_verdict") == "uncertain"]

    def ref(r):
        doi = f" doi:{r['doi']}" if r.get("doi") else ""
        return f"- PMID {r['pmid']} - {r.get('title','')} ({r.get('journal','')}, {r.get('year','')}){doi}"

    md = []
    md.append(f"# Literature Search Report - {profile.device_name}")
    md.append(f"*Manufacturer: {profile.manufacturer} ? Class {profile.classification} "
              f"({profile.classification_rule}) ? Scope hash: `{profile.run_scope_hash()}`*")
    md.append("\n> **Status:** First-draft regulatory artifact generated by Vigil. "
              "To be reviewed, completed, and signed by the PRRC. Vigil describes "
              "evidence; it does not conclude on safety, performance, or compliance.\n")

    md.append("## A5.1 Background")
    md.append(f"- **Device:** {profile.device_name} - {profile.device_description}")
    md.append(f"- **Intended purpose:** {profile.intended_purpose}")
    md.append(f"- **Comparator device(s):** {', '.join(profile.comparator_devices) or '-'}")
    md.append("- **Equivalence statement:** "
              "[PRRC TO COMPLETE: Demonstration of equivalence - MEDDEV Appendix A1.]")

    md.append("\n## A5.2 Objective (PICO)")
    md.append(f"- **Track 1 (device-specific):** Performance and safety of "
              f"{profile.device_name} / equivalent devices in {', '.join(profile.medical_condition)}.")
    md.append(f"- **Track 2 (state of the art):** Current clinical knowledge on "
              f"{', '.join(profile.therapeutic_area)} for {', '.join(profile.medical_condition)}.")

    md.append("\n## A5.3 Methods")
    md.append("- **Databases:** PubMed/MEDLINE via NCBI E-utilities. "
              "*(V1 limitation: Embase/Cochrane not searched; PRRC may supplement.)*")
    md.append(f"- **Date range:** {profile.date_from} to {profile.date_to}")
    md.append(f"- **Languages:** {', '.join(profile.languages)}")
    md.append("- **Search strings (verbatim):**")
    md.append(f"\n  *Track 1 - device-specific:*\n  ```\n  {queries['device_specific']}\n  ```")
    md.append(f"\n  *Track 2 - state of the art:*\n  ```\n  {queries['state_of_art']}\n  ```")

    t1_incl, t1_excl = profile.criteria_for_track("device_specific")
    t2_incl, t2_excl = profile.criteria_for_track("state_of_art")
    md.append("- **Track 1 (device-specific) selection criteria** - primary clinical "
              "evidence on the device/equivalent:")
    md.append("  - *Inclusion:*")
    md += [f"    - {c}" for c in t1_incl]
    md.append("  - *Exclusion:*")
    md += [f"    - {c}" for c in t1_excl]
    md.append("- **Track 2 (state of the art) selection criteria** - per MEDDEV 2.7/1 "
              "rev 4 Appendix A4, the SOTA evidence base includes clinical practice "
              "guidelines, consensus statements, systematic reviews, meta-analyses, "
              "and HTA reviews, not only primary trials:")
    md.append("  - *Inclusion:*")
    md += [f"    - {c}" for c in t2_incl]
    md.append("  - *Exclusion:*")
    md += [f"    - {c}" for c in t2_excl]
    md.append("- **Deduplication:** by PMID across tracks (papers in both tracks tagged `both`).")
    md.append("- **Full-text retrieval & appraisal plan:** Two-phase. "
              "(1) Abstract-level screening and preliminary extraction. "
              "(2) Full-text appraisal (MEDDEV Appendix A6). Full text is obtained "
              "automatically wherever a legal open-access copy exists - via PubMed "
              "Central (PMC) and Unpaywall - and appraised without manual effort. "
              "Only papers with no open-access copy are routed to the PRRC for manual "
              "upload. Vigil never circumvents a paywall; the PRRC supplies any file "
              "that is not openly available. Papers whose full text is neither "
              "retrieved nor uploaded are flagged `appraisal incomplete` (MEDDEV ?9.3).")

    md.append("\n## Results - counts per stage")
    c = counts.as_dict()
    registry = [r for r in incl if r.get("appraisal_status") == "registry_evidence"]
    incomplete = [r for r in incl if r.get("appraisal_status") == "appraisal_incomplete"]
    appraised = [r for r in incl if r.get("appraisal_status") == "complete"]

    # Retrieval-source breakdown (audit: HOW each full text was obtained)
    def _src_count(src):
        return sum(1 for r in appraised if r.get("retrieval_source") == src)
    n_pmc = _src_count("pmc_xml")
    n_uw = _src_count("unpaywall_pdf")
    n_upload = _src_count("prrc_upload")

    md.append(f"- Records identified: {c['db_records']} "
              f"(duplicates removed: {c['duplicates_removed']})")
    md.append(f"- Screened: {c['screened']} -> included {len(incl)}, "
              f"excluded {len(excl)}, uncertain (human review) {len(unc)}")
    md.append(f"- Full text appraised (MEDDEV A6): {len(appraised)} - "
              f"auto-retrieved {n_pmc + n_uw} (PMC {n_pmc}, Unpaywall {n_uw}), "
              f"PRRC upload {n_upload}")
    md.append(f"- Trial registrations identified (registry evidence; counted as "
              f"included, never routed to full-text appraisal): {len(registry)}")
    md.append(f"- Appraisal incomplete (no open-access copy; awaiting upload): "
              f"{len(incomplete)}")
    md.append(f"- **Studies fully appraised and included in analysis: {c['included']}** "
              f"(full-text appraised {len(appraised)} + registry evidence {len(registry)})")

    def ref_src(r):
        labels = {"pmc_xml": "PMC OA", "unpaywall_pdf": "Unpaywall OA",
                  "prrc_upload": "PRRC upload"}
        src = labels.get(r.get("retrieval_source"), "full text")
        vr = r.get("verification_result")
        vlabel = {"verified_doi": "DOI-verified", "verified_title": "title-verified"}.get(vr)
        tag = f"{src}, {vlabel}" if vlabel else src
        return ref(r) + f"  _[{tag}]_"

    md.append("\n### Fully appraised studies (full text reviewed)")
    md += [ref_src(r) for r in appraised] or ["- (none yet - awaiting retrieval/upload)"]

    if registry:
        md.append("\n### Trial registrations identified (registry evidence)")
        md.append("*These are trial registrations (e.g. ClinicalTrials.gov), not "
                  "published papers. They are counted as included evidence that a "
                  "study exists - including unpublished studies - per the "
                  "publication-bias expectation in MEDDEV 2.7/1 rev 4. A registration "
                  "is never routed to PDF upload or full-text appraisal.*")
        md += [ref(r) for r in registry]

    unverified = [r for r in incomplete
                  if r.get("retrieval_source") == "auto_unverified"]
    no_oa = [r for r in incomplete if r not in unverified]

    if no_oa:
        md.append("\n### Papers flagged `appraisal incomplete` (no open-access copy found)")
        md.append("*These passed relevance screening but no legal open-access full "
                  "text was found. The PRRC should upload the full text, or document "
                  "the justification for exclusion from analysis.*")
        md += [ref(r) for r in no_oa]

    if unverified:
        md.append("\n### Papers where an open-access copy was found but COULD NOT be verified")
        md.append("*Vigil retrieved a candidate full text but could not confirm it is "
                  "the correct paper (DOI/title mismatch), so it was NOT appraised. "
                  "The PRRC should retrieve and upload the correct full text.*")
        for r in unverified:
            reason = r.get("verification_reason") or "identity not confirmed"
            md.append(ref(r) + f"  _[unverified: {reason}]_")
    if unc:
        md.append("\n### Flagged for human review (uncertain screening verdict)")
        md += [ref(r) for r in unc]

    md.append("\n## PRISMA 2020 flow diagram")
    md.append(prisma_svg)
    return "\n".join(md)


# --- CER Word-doc narrative (outputs.generate_cer_md's injectable narrative_fn) -----
# outputs.generate_cer_md builds the actual downloadable CER (full Appendix A9
# structure: equivalence table, PRRC judgement placeholders, honest appraisal
# counts, etc.) and calls narrative_fn(section_key, context) -> str at five
# descriptive slots. This is the ONLY narrative generator wired into that path -
# generated once, on demand, when the Document Set step builds the CER.

_SECTION_TITLES = {
    "summary": "1. Summary",
    "state_of_art": "3. Clinical background, current knowledge, state of the art",
    "evidence_summary": "5. Summary of the clinical data and appraisal",
    "performance": "6.1 Analysis of the clinical data - Performance",
    "safety": "6.2 Analysis of the clinical data - Safety",
}

_SECTION_INSTRUCTIONS = {
    "summary": (
        "Give one short paragraph: how many studies were fully appraised, and "
        "in one sentence what they broadly cover (device-specific vs state of "
        "the art). Do not repeat exact counts already stated elsewhere in the "
        "document - keep this to a narrative overview."),
    "state_of_art": (
        "Describe current clinical knowledge / standard of care for the "
        "condition and technology named below, using ONLY records tagged "
        "\"track\": \"state_of_art\" (Track 2). If none are present, say so "
        "plainly rather than writing generically.\n"
        "Condition(s): {condition}\nTechnology: {technology}"),
    "evidence_summary": (
        "For each record tagged \"track\": \"device_specific\" (Track 1), "
        "summarise what the study is and its MEDDEV A6 appraisal "
        "(methodological quality, relevance, data contribution), citing its "
        "PMID."),
    "performance": (
        "Summarise device performance data reported in the "
        "\"device_specific\" (Track 1) records, with a PMID citation for "
        "every figure."),
    "safety": (
        "Summarise adverse-event / safety data reported in the "
        "\"device_specific\" (Track 1) records, with a PMID citation for "
        "every figure."),
}

_NO_EVIDENCE_NOTE = ("*No fully appraised full-text evidence is available yet "
                     "for this section.*")

# Records found by both search tracks are tagged "both" (pubmed.dedup) and are
# treated as device evidence, matching DeviceProfile.criteria_for_track's
# existing convention (a paper appearing in both tracks is considered device
# evidence, screened against Track 1 criteria).
_DEVICE_SPECIFIC_TRACKS = {"device_specific", "both"}

# Split points in the reordered template (Block 5X): device fields are stable
# across all 5 narrative calls; the evidence JSON (after scoping, below) is
# stable across calls that share the same track scope (evidence_summary,
# performance, and safety all draw on the same device-specific set);
# section_title/section_instructions vary on every call and stay uncached.
_EVIDENCE_MARKER = "\nAPPRAISED EVIDENCE AVAILABLE"
_SECTION_MARKER = "\nSECTION TO WRITE:"


def _scope_for_section(section_key: str, appraised: list[dict]) -> list[dict]:
    """Filter appraised records to the track(s) this section is allowed to
    cite (Block 5X - fixes a real gap between prompt and code).

    The prompt has always said "use only the track relevant to this
    section," but the caller was sending every appraised record to every
    section regardless of track and trusting the model to self-filter -
    concretely, `state_of_art` was receiving Track 1 (device-specific) data
    it must never reference (MEDDEV/MDCG require the two kept separate).
    This scopes the evidence in code instead of relying on the model.

    'summary' is a whole-run overview and intentionally still sees
    everything."""
    if section_key == "state_of_art":
        return [r for r in appraised if r.get("track") == "state_of_art"]
    if section_key in ("evidence_summary", "performance", "safety"):
        return [r for r in appraised if r.get("track") in _DEVICE_SPECIFIC_TRACKS]
    return appraised  # "summary"


def _record_payload(r: dict) -> dict:
    """Compact, LLM-ready view of one appraised record: identity + parsed
    appraisal/extraction data. Never forwards the raw DB row (unrelated
    columns, an already-JSON-encoded string) into the prompt."""
    payload = {"pmid": r.get("pmid"), "title": r.get("title", ""),
              "track": r.get("track", "")}
    if r.get("extraction_json"):
        try:
            payload["appraisal"] = json.loads(r["extraction_json"])
        except json.JSONDecodeError:
            pass
    return payload


def make_narrative_fn(call=None):
    """Build a narrative_fn(section_key, context) -> str for
    outputs.generate_cer_md: one small, focused LLM call per section, grounded
    ONLY in context["appraised"] (the fully appraised full-text records
    outputs.py already computed). Returns an honest placeholder instead of
    calling the LLM when there is no appraised evidence at all, rather than
    asking it to write prose from nothing.

    `call` is a text-returning callable (model, system, user, max_tokens) -> str.
    Defaults to llm.call_text; tests inject a stub so this runs offline."""
    from llm import call_text, split_stable_variable
    call = call or call_text

    tmpl = load_prompt(config.PROMPT_CER_NARRATIVE)
    device_tmpl, _tail = split_stable_variable(tmpl, _EVIDENCE_MARKER)
    evidence_tmpl, section_tmpl = split_stable_variable(_tail, _SECTION_MARKER)

    def narrative_fn(section_key, context):
        appraised = context.get("appraised") or []
        scoped = _scope_for_section(section_key, appraised)
        payload = [_record_payload(r) for r in scoped]
        if not payload:
            return _NO_EVIDENCE_NOTE
        profile = context.get("profile")
        instructions = _SECTION_INSTRUCTIONS.get(section_key, "")
        if section_key == "state_of_art":
            instructions = instructions.format(
                condition=context.get("condition", ""),
                technology=context.get("technology", ""))

        # Device fields + the (now track-scoped) evidence JSON come first,
        # section title/instructions last - the byte order a future
        # cache_control breakpoint needs (the evidence JSON is identical
        # across every call that shares this section's track scope; the
        # trailing section text varies on every call). No breakpoint is set
        # here yet - just the ordering (Block 5X).
        user = (
            device_tmpl.format(
                device_name=getattr(profile, "device_name", "") if profile else "",
                intended_purpose=getattr(profile, "intended_purpose", "") if profile else "")
            + evidence_tmpl.format(context_json=json.dumps(payload, indent=2))
            + section_tmpl.format(
                section_title=_SECTION_TITLES.get(section_key, section_key),
                section_instructions=instructions,
            )
        )
        return call(config.MODEL_DRAFT, _SYSTEM, user, config.MAX_TOKENS_DRAFT)

    return narrative_fn
