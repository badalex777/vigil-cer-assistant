"""Vigil — Stage: search report + CER first-draft section assembly."""
from __future__ import annotations
import json

import config
import db
from llm import load_prompt

_SYSTEM = "You write only the requested Markdown. No preamble."


def build_search_report(profile, queries: dict, counts, prisma_svg: str,
                        records: list[dict]) -> str:
    """The audit-ready literature search report — a regulatory artifact submitted
    to the Notified Body. Deterministic; not LLM-generated (it documents the
    protocol verbatim). MEDDEV 2.7/1 rev 4 Appendix A5 structure."""
    incl = [r for r in records if r.get("screen_verdict") == "include"]
    excl = [r for r in records if r.get("screen_verdict") == "exclude"]
    unc = [r for r in records if r.get("screen_verdict") == "uncertain"]

    def ref(r):
        doi = f" doi:{r['doi']}" if r.get("doi") else ""
        return f"- PMID {r['pmid']} — {r.get('title','')} ({r.get('journal','')}, {r.get('year','')}){doi}"

    md = []
    md.append(f"# Literature Search Report — {profile.device_name}")
    md.append(f"*Manufacturer: {profile.manufacturer} · Class {profile.classification} "
              f"({profile.classification_rule}) · Scope hash: `{profile.run_scope_hash()}`*")
    md.append("\n> **Status:** First-draft regulatory artifact generated by Vigil. "
              "To be reviewed, completed, and signed by the PRRC. Vigil describes "
              "evidence; it does not conclude on safety, performance, or compliance.\n")

    md.append("## A5.1 Background")
    md.append(f"- **Device:** {profile.device_name} — {profile.device_description}")
    md.append(f"- **Intended purpose:** {profile.intended_purpose}")
    md.append(f"- **Comparator device(s):** {', '.join(profile.comparator_devices) or '—'}")
    md.append("- **Equivalence statement:** "
              "[PRRC TO COMPLETE: Demonstration of equivalence — MEDDEV Appendix A1.]")

    md.append("\n## A5.2 Objective (PICO)")
    md.append(f"- **Track 1 (device-specific):** Performance and safety of "
              f"{profile.device_name} / equivalent devices in {', '.join(profile.medical_condition)}.")
    md.append(f"- **Track 2 (state of the art):** Current clinical knowledge on "
              f"{', '.join(profile.therapeutic_area)} for {', '.join(profile.medical_condition)}.")

    md.append("\n## A5.3 Methods")
    md.append("- **Databases:** PubMed/MEDLINE via NCBI E-utilities. "
              "*(V1 limitation: Embase/Cochrane not searched; PRRC may supplement.)*")
    md.append(f"- **Date range:** {profile.date_from} to {profile.date_to}")
    md.append(f"- **Languages:** {', '.join(profile.languages)}")
    md.append("- **Search strings (verbatim):**")
    md.append(f"\n  *Track 1 — device-specific:*\n  ```\n  {queries['device_specific']}\n  ```")
    md.append(f"\n  *Track 2 — state of the art:*\n  ```\n  {queries['state_of_art']}\n  ```")
    md.append("- **Inclusion criteria:**")
    md += [f"  - {c}" for c in profile.inclusion_criteria]
    md.append("- **Exclusion criteria:**")
    md += [f"  - {c}" for c in profile.exclusion_criteria]
    md.append("- **Deduplication:** by PMID across tracks (papers in both tracks tagged `both`).")
    md.append("- **Full-text retrieval & appraisal plan:** Two-phase. "
              "(1) Abstract-level screening and preliminary extraction. "
              "(2) Full-text appraisal (MEDDEV Appendix A6). Full text is obtained "
              "automatically wherever a legal open-access copy exists — via PubMed "
              "Central (PMC) and Unpaywall — and appraised without manual effort. "
              "Only papers with no open-access copy are routed to the PRRC for manual "
              "upload. Vigil never circumvents a paywall; the PRRC supplies any file "
              "that is not openly available. Papers whose full text is neither "
              "retrieved nor uploaded are flagged `appraisal incomplete` (MEDDEV §9.3).")

    md.append("\n## Results — counts per stage")
    c = counts.as_dict()
    incomplete = [r for r in incl if r.get("appraisal_status") == "appraisal_incomplete"]
    appraised = [r for r in incl if r.get("appraisal_status") == "complete"]

    # Retrieval-source breakdown (audit: HOW each full text was obtained)
    def _src_count(src):
        return sum(1 for r in appraised if r.get("retrieval_source") == src)
    n_pmc = _src_count("pmc_xml")
    n_uw = _src_count("unpaywall_pdf")
    n_upload = _src_count("prrc_upload")

    md.append(f"- Records identified: {c['db_records']} "
              f"(duplicates removed: {c['duplicates_removed']})")
    md.append(f"- Screened: {c['screened']} → included {len(incl)}, "
              f"excluded {len(excl)}, uncertain (human review) {len(unc)}")
    md.append(f"- Full text appraised (MEDDEV A6): {len(appraised)} — "
              f"auto-retrieved {n_pmc + n_uw} (PMC {n_pmc}, Unpaywall {n_uw}), "
              f"PRRC upload {n_upload}")
    md.append(f"- Appraisal incomplete (no open-access copy; awaiting upload): "
              f"{len(incomplete)}")
    md.append(f"- **Studies fully appraised and included in analysis: {c['included']}**")

    def ref_src(r):
        labels = {"pmc_xml": "PMC OA", "unpaywall_pdf": "Unpaywall OA",
                  "prrc_upload": "PRRC upload"}
        src = labels.get(r.get("retrieval_source"), "full text")
        vr = r.get("verification_result")
        vlabel = {"verified_doi": "DOI-verified", "verified_title": "title-verified"}.get(vr)
        tag = f"{src}, {vlabel}" if vlabel else src
        return ref(r) + f"  _[{tag}]_"

    md.append("\n### Fully appraised studies (full text reviewed)")
    md += [ref_src(r) for r in appraised] or ["- (none yet — awaiting retrieval/upload)"]

    unverified = [r for r in incomplete
                  if r.get("retrieval_source") == "auto_unverified"]
    no_oa = [r for r in incomplete if r not in unverified]

    if no_oa:
        md.append("\n### Papers flagged `appraisal incomplete` (no open-access copy found)")
        md.append("*These passed relevance screening but no legal open-access full "
                  "text was found. The PRRC should upload the full text, or document "
                  "the justification for exclusion from analysis.*")
        md += [ref(r) for r in no_oa]

    if unverified:
        md.append("\n### Papers where an open-access copy was found but COULD NOT be verified")
        md.append("*Vigil retrieved a candidate full text but could not confirm it is "
                  "the correct paper (DOI/title mismatch), so it was NOT appraised. "
                  "The PRRC should retrieve and upload the correct full text.*")
        for r in unverified:
            reason = r.get("verification_reason") or "identity not confirmed"
            md.append(ref(r) + f"  _[unverified: {reason}]_")
    if unc:
        md.append("\n### Flagged for human review (uncertain screening verdict)")
        md += [ref(r) for r in unc]

    md.append("\n## PRISMA 2020 flow diagram")
    md.append(prisma_svg)
    return "\n".join(md)


def build_cer_section(profile, appraised_records: list[dict],
                      incomplete_records: list[dict],
                      pms_signals: list[dict], call=None) -> str:
    """The CER first-draft literature analysis section (LLM-assembled from
    extracted data only). MEDDEV 2.7/1 rev 4 §11 / Appendix A9.

    Narrative is built from FULLY APPRAISED (full-text) papers. Papers still
    `appraisal incomplete` are passed as an explicit list so the draft flags them
    rather than silently using thin abstract data as if it were appraised.

    `call` is a text-returning callable (model, system, user, max_tokens) -> str.
    Defaults to llm.call_text; tests inject a stub."""
    from llm import call_text
    call = call or call_text
    extracted = []
    for r in appraised_records:
        if r.get("extraction_json"):
            try:
                extracted.append(json.loads(r["extraction_json"]))
            except json.JSONDecodeError:
                pass
    incomplete = [
        {"pmid": r["pmid"], "title": r.get("title", ""),
         "status": "appraisal_incomplete — full text not retrieved/appraised"}
        for r in incomplete_records
    ]
    tmpl = load_prompt(config.PROMPT_DRAFT)
    user = tmpl.format(
        device_name=profile.device_name,
        intended_purpose=profile.intended_purpose,
        extracted_json=json.dumps(extracted, indent=2),
        appraisal_incomplete=json.dumps(incomplete, indent=2) if incomplete else "[none]",
        pms_signals=json.dumps(pms_signals, indent=2) if pms_signals else "[none]",
    )
    return call(config.MODEL_DRAFT, _SYSTEM, user, config.MAX_TOKENS_DRAFT)
